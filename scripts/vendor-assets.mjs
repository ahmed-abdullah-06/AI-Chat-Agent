// Vendors third-party browser assets (fonts + icon font) into src/public/vendor
// so the production build has zero external dependencies: faster, private and
// fully functional offline. Runs automatically before `vite build`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const nm = path.join(root, 'node_modules');
const vendor = path.join(root, 'src', 'public', 'vendor');

const onlyWoff2 = (css) =>
  css
    // fontsource ships woff fallbacks we never request
    .replace(/,\s*url\([^)]*\.woff\) format\('woff'\)/g, '')
    // tabler ships eot/ttf/woff chains we never request
    .replace(/src:url\("\.\/fonts\/tabler-icons\.eot[^}]*format\("truetype"\)\}/, 'src:url("./fonts/tabler-icons.woff2") format("woff2")}');

const write = (rel, content) => {
  const target = path.join(vendor, rel);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, content);
};

const copy = (from, rel) => {
  const target = path.join(vendor, rel);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.copyFileSync(from, target);
};

fs.rmSync(vendor, { recursive: true, force: true });
fs.mkdirSync(vendor, { recursive: true });

// --- Tabler icon font -------------------------------------------------------
const tablerPkg = path.join(nm, '@tabler', 'icons-webfont');
const tablerCss = onlyWoff2(fs.readFileSync(path.join(tablerPkg, 'tabler-icons.min.css'), 'utf8'));
write(path.join('icons', 'tabler-icons.min.css'), tablerCss);
copy(path.join(tablerPkg, 'fonts', 'tabler-icons.woff2'), path.join('icons', 'fonts', 'tabler-icons.woff2'));

// --- Web fonts --------------------------------------------------------------
const families = [
  { dir: 'syne', match: /^latin(?:-ext)?-(?:400|500|600|700|800)\.css$/ },
  { dir: 'dm-sans', match: /^latin(?:-ext)?-(?:300|400|500|700)(?:-italic)?\.css$/ }
];

const fontFace = [];
const woff2 = new Set();

for (const family of families) {
  const pkg = path.join(nm, '@fontsource', family.dir);
  const entries = fs.readdirSync(pkg).filter((f) => family.match.test(f)).sort();
  if (!entries.length) throw new Error(`No matching @fontsource/${family.dir} css files found`);

  for (const file of entries) {
    const css = onlyWoff2(fs.readFileSync(path.join(pkg, file), 'utf8'));
    fontFace.push(`/* ${family.dir}/${file} */\n${css.trim()}`);
    for (const m of css.matchAll(/url\(\.\/files\/([^)]+\.woff2)\)/g)) woff2.add(m[1]);
  }

  const filesDir = path.join(pkg, 'files');
  for (const font of woff2) {
    const source = path.join(filesDir, font);
    if (fs.existsSync(source)) copy(source, path.join('fonts', 'files', font));
  }
  woff2.clear();
}

write(path.join('fonts', 'fonts.css'), `/* Self-hosted web fonts (generated by scripts/vendor-assets.mjs) */\n${fontFace.join('\n\n')}\n`);

const sizeOf = (rel) => {
  try {
    return fs.statSync(path.join(vendor, rel)).size;
  } catch {
    return 0;
  }
};
console.log(
  `[vendor] icons: ${(sizeOf(path.join('icons', 'fonts', 'tabler-icons.woff2')) / 1024).toFixed(0)} KB · ` +
    `fonts.css: ${(sizeOf(path.join('fonts', 'fonts.css')) / 1024).toFixed(1)} KB · ` +
    `woff2 files: ${fs.readdirSync(path.join(vendor, 'fonts', 'files')).length}`
);
console.log('[vendor] assets written to src/public/vendor');
